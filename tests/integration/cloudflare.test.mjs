import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {startCloudflareLocal} from '../../scripts/cloudflare-local.mjs';
import {createCloudAccounts} from '../../src/server/cloudflare/accounts.mjs';

// Exercises the built Worker with real D1 and SQLite Durable Object simulations.
// Run after build:cloud, separately from source-only npm test.
test('cloud accounts, owner controls and durable progress survive a runtime replacement',async t=>{
  const persistTo=await mkdtemp(path.join(tmpdir(),'khutwa-cloud-test-'));
  let app=await startCloudflareLocal({persistTo});
  t.after(async()=>{await app.close();await rm(persistTo,{recursive:true,force:true});});
  const request=async(route,{cookie='',owner,body,headers={}}={})=>{
    const response=await fetch(new URL(route,app.base),{method:body?'POST':'GET',redirect:'manual',headers:{Cookie:cookie,...(owner?{'X-Progress-Owner':`account:${owner}`} : {}),...(body?{'Content-Type':'application/json'}:{}),...headers},...(body?{body:JSON.stringify(body)}:{})});
    const text=await response.text();
    return {status:response.status,cookie:response.headers.get('set-cookie')?.split(';')[0],body:response.headers.get('content-type')?.includes('json')?JSON.parse(text):text};
  };
  const registration=await request('/api/auth/register',{body:{username:'cloud-student',password:'Student123',phone:'0598000041',curriculum:'gaza',path:'scientific',isOwner:true}});
  assert.equal(registration.status,201,JSON.stringify(registration.body));
  assert.equal(registration.body.account.isOwner,false);
  const student=registration.body.account,studentCookie=registration.cookie;
  const store=createCloudAccounts(app.database);
  const {account:owner}=await store.createAccount({username:'cloud-owner',password:'Owner1234',curriculum:'gaza',path:'scientific'});
  await app.database.prepare("UPDATE accounts SET staff_role='owner' WHERE id=?").bind(Number(owner.id)).run();
  const ownerCookie=`tawjihi_session=${(await store.createSession(owner.id)).token}`;
  const endpoint=`/api/owner/students/${student.id}`;
  assert.equal((await request('/')).status,200);
  assert.equal((await request(endpoint)).status,401);
  assert.equal((await request(endpoint,{cookie:studentCookie})).status,403);
  assert.equal((await request('/admin.html',{cookie:studentCookie})).status,403);
  assert.equal((await request('/admin',{cookie:studentCookie})).status,403);
  assert.equal((await request('/students',{cookie:ownerCookie})).status,200);
  assert.equal((await request(endpoint,{cookie:ownerCookie,body:{action:'grant',version:0,duration:'week'},headers:{Origin:'https://attacker.example'}})).status,403);
  let detail=(await request(endpoint,{cookie:ownerCookie})).body;
  const change=async(action,extra={})=>request(endpoint,{cookie:ownerCookie,body:{action,version:detail.version,...extra}});
  assert.equal((await change('grant',{duration:'week'})).status,200);
  detail=(await request(endpoint,{cookie:ownerCookie})).body;
  assert.equal(detail.accountType,'subscribed');
  assert.ok(Date.parse(detail.subscriptionExpiresAt)>Date.now()+6*86400000);
  assert.equal((await request(endpoint,{cookie:ownerCookie,body:{action:'revoke',version:0}})).status,409);
  const catalog=JSON.parse(await readFile(path.join('_site',/name="khutwa-catalog" content="([^"]+)"/.exec(await readFile('_site/index.html','utf8'))[1]),'utf8'));
  const lesson=JSON.parse(await readFile(path.join('_site',catalog.lessons['ict:database-management']),'utf8'));
  const step=lesson.steps.find(step=>step.type==='mcq');
  const part=lesson.parts.find(part=>part.stepIds.includes(step.id));
  const answer={id:'cloud-answer-1',type:'answer',subjectId:'ict',lessonId:'database-management',partId:part.id,stepId:step.id,correct:true};
  assert.equal((await request('/api/progress',{cookie:studentCookie,owner:owner.id})).status,409);
  const saved=await request('/api/progress',{cookie:studentCookie,owner:student.id,body:answer});
  assert.equal(saved.status,200,JSON.stringify(saved.body));
  const duplicate=await request('/api/progress',{cookie:studentCookie,owner:student.id,body:answer});
  assert.deepEqual(duplicate.body.records,saved.body.records,'retries do not duplicate progress or XP');
  await app.close();
  app=await startCloudflareLocal({persistTo});
  const restored=await request('/api/progress',{cookie:studentCookie,owner:student.id});
  assert.deepEqual(restored.body.records,saved.body.records,'progress survives a new Worker runtime');
  assert.equal((await request('/api/app-state')).body.resetId,null);
  detail=(await request(endpoint,{cookie:ownerCookie})).body;
  assert.ok(detail.questionsSolved>0);
  assert.equal((await change('revoke')).status,200);
  detail=(await request(endpoint,{cookie:ownerCookie})).body;
  assert.equal(detail.accountType,'free');
  assert.equal((await change('grant',{duration:'permanent'})).status,200);
  detail=(await request(endpoint,{cookie:ownerCookie})).body;
  assert.equal(detail.subscriptionExpiresAt,null);
  await app.database.prepare("UPDATE accounts SET subscription_expires_at=? WHERE id=?").bind('2020-01-01T00:00:00.000Z',Number(student.id)).run();
  assert.equal((await request('/api/auth/session',{cookie:studentCookie})).body.account.accountType,'free');
  assert.equal((await change('suspend')).status,200);
  assert.equal((await request('/api/auth/session',{cookie:studentCookie})).body.account,null);
  assert.equal((await request('/api/auth/sign-in',{body:{identifier:'cloud-student',password:'Student123'}})).status,403);
  detail=(await request(endpoint,{cookie:ownerCookie})).body;
  assert.equal((await change('restore')).status,200);
  detail=(await request(endpoint,{cookie:ownerCookie})).body;
  assert.equal((await change('delete',{confirmUsername:'wrong-student'})).status,422);
  const deleted=await change('delete',{confirmUsername:student.username});
  assert.equal(deleted.status,200,JSON.stringify(deleted.body));
  assert.equal(deleted.body.cleanupPending,false);
  assert.equal((await request(endpoint,{cookie:ownerCookie})).status,404);
  assert.equal((await app.database.prepare('SELECT count(*) n FROM account_identifiers WHERE account_id=?').bind(Number(student.id)).first()).n,0);
  assert.equal((await app.database.prepare('SELECT count(*) n FROM admin_audit WHERE student_id=?').bind(Number(student.id)).first()).n,6);
  assert.equal((await app.database.prepare('SELECT count(*) n FROM student_deletions').first()).n,0);
});
